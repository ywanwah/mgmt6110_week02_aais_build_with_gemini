// Helper to generate realistic sparkline & historical price curves
function generateHistory(basePrice: number, volatility: number = 0.015, trend: number = 0.002) {
  const generateSeries = (count: number, intervalMinutes: number) => {
    const points = [];
    let current = basePrice * (1 - (count * trend) / 2);
    const now = new Date();

    for (let i = 0; i < count; i++) {
      const timeDate = new Date(now.getTime() - (count - i) * intervalMinutes * 60 * 1000);
      const timeStr = count > 30 ? timeDate.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }) : timeDate.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      
      const change = (Math.random() - 0.48 + trend) * volatility * current;
      current = Math.max(current + change, basePrice * 0.5);
      
      const high = current * (1 + Math.random() * 0.004);
      const low = current * (1 - Math.random() * 0.004);
      const open = (current + low) / 2;

      points.push({
        time: timeStr,
        price: parseFloat(current.toFixed(2)),
        open: parseFloat(open.toFixed(2)),
        high: parseFloat(high.toFixed(2)),
        low: parseFloat(low.toFixed(2)),
        volume: Math.floor(Math.random() * 500000) + 50000,
      });
    }
    return points;
  };

  const dayPoints = generateSeries(24, 15);
  const sparkline = dayPoints.slice(-12).map((p) => p.price);

  return {
    sparkline,
    history: {
      '1D': dayPoints,
      '5D': generateSeries(30, 240),
      '1M': generateSeries(30, 1440),
      '6M': generateSeries(26, 10080),
      '1Y': generateSeries(52, 10080),
      'ALL': generateSeries(60, 43200),
    },
  };
}

